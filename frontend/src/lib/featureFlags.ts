/**
 * 前端功能開關。
 *
 * ## 為什麼是程式碼常數，不是環境變數
 *
 * 開關的開與關要跟著正常的發版流程走（PR → review → staging → main），才有紀錄、
 * 有人看過。環境變數改起來快，但也代表「誰在什麼時候把功能打開的」不會留下痕跡 ——
 * 這正是這個檔案要避免的情況。
 *
 * 打開的動作就是把 `false` 改成 `true`、開一張 PR、走一次發版。
 */

